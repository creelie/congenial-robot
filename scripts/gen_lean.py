def order(n, covers):
    le = [[i == j for j in range(n)] for i in range(n)]
    for c in covers.split():
        a, b = map(int, c.split("<"))
        le[a][b] = True
    for k in range(n):
        for i in range(n):
            for j in range(n):
                if le[i][k] and le[k][j]:
                    le[i][j] = True
    return le


def tables(n, le):
    def lub(a, b):
        ub = [z for z in range(n) if le[a][z] and le[b][z]]
        least = [z for z in ub if all(le[z][w] for w in ub)]
        assert len(least) == 1
        return least[0]

    def glb(a, b):
        lb = [z for z in range(n) if le[z][a] and le[z][b]]
        great = [z for z in lb if all(le[w][z] for w in lb)]
        assert len(great) == 1
        return great[0]

    sup = [[lub(a, b) for b in range(n)] for a in range(n)]
    inf = [[glb(a, b) for b in range(n)] for a in range(n)]
    return sup, inf


def derivation(n, sup, inf, base):
    """Joins and meets that take the set `base` to the whole lattice, in order."""
    known = list(base)
    steps = []
    while len(known) < n:
        new = None
        for a in known:
            for b in known:
                for op, t in (("sup", sup), ("inf", inf)):
                    if t[a][b] not in known:
                        new = (t[a][b], op, a, b)
                        break
                if new:
                    break
            if new:
                break
        assert new, "the set does not generate the lattice"
        known.append(new[0])
        steps.append(new)
    return steps


def emit(key, spec):
    T, n = spec["name"], spec["n"]
    le = order(n, spec["covers"])
    sup, inf = tables(n, le)
    M = spec["M"]
    C = [c for c in range(n) if c not in M]
    for a in M:
        for b in M:
            assert sup[a][b] in M and inf[a][b] in M
    out = []
    w = out.append
    ctors = " | ".join(f"e{i}" for i in range(n))
    w(f"/-- The {n} elements; `e0` is the least and `e{n - 1}` the greatest element. -/")
    w(f"inductive {T} where")
    w(f"  | {ctors}")
    w("  deriving DecidableEq")
    w("")
    w(f"namespace {T}")
    w("")
    elems = ", ".join(f"e{i}" for i in range(n))
    w(f"instance : Fintype {T} := Fintype.ofList [{elems}] (by intro x; cases x <;> simp)")
    w("")
    for op, t in (("sup", sup), ("inf", inf)):
        w(f"/-- the {'join' if op == 'sup' else 'meet'} table -/")
        w(f"def {op} : {T} → {T} → {T}")
        for a in range(n):
            row = "  " + " ".join(f"| e{a}, e{b} => e{t[a][b]}" for b in range(n))
            w(row)
        w("")
    w(f"instance : Max {T} := ⟨sup⟩")
    w(f"instance : Min {T} := ⟨inf⟩")
    w("")
    w(f"instance : Lattice {T} :=")
    w("  Lattice.mk' (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)")
    w("")
    w(f"instance : DecidableLE {T} := fun a b => inferInstanceAs (Decidable (a ⊔ b = b))")
    w(f"instance : DecidableLT {T} := decidableLTOfDecidableLE")
    w("")
    covs = " ".join(f"`e{c.split('<')[0]} ⋖ e{c.split('<')[1]}`" for c in spec["covers"].split())
    w(f"/-- The covering pairs are {covs}. -/")
    w(f"theorem covBy_iff (a b : {T}) : a ⋖ b ↔ (a < b ∧ ∀ c : {T}, a < c → ¬c < b) := Iff.rfl")
    w("")
    w(f"instance : DecidableRel (α := {T}) (· ⋖ ·) := fun a b => decidable_of_iff _ (covBy_iff a b).symm")
    w("")
    w("/-- membership in `M` -/")
    w(f"def inM : {T} → Bool")
    w("  " + " ".join(f"| e{i} => {'true' if i in M else 'false'}" for i in range(n)))
    w("")
    mset = ", ".join(f"e{i}" for i in M)
    w(f"/-- The sublattice `M = {{{mset}}}`. -/")
    w(f"def M : Sublattice {T} where")
    w("  carrier := {x | inM x = true}")
    w("  supClosed' := fun a ha b hb => by")
    w(f"    have key : ∀ a b : {T}, inM a = true → inM b = true → inM (a ⊔ b) = true := by decide +kernel")
    w("    exact key a b ha hb")
    w("  infClosed' := fun a ha b hb => by")
    w(f"    have key : ∀ a b : {T}, inM a = true → inM b = true → inM (a ⊓ b) = true := by decide +kernel")
    w("    exact key a b ha hb")
    w("")
    w(f"theorem mem_M (x : {T}) : x ∈ M ↔ inM x = true := Iff.rfl")
    w("")
    w("/-- `M` is a maximal proper sublattice: any sublattice that contains `M` and one more element")
    w("contains everything. For each element `c` outside `M` the proof lists the joins and meets that")
    w("generate the whole lattice from `M` and `c`. -/")
    w("theorem isCoatom_M : IsCoatom M := by")
    w("  refine ⟨fun h => ?_, fun S hS => ?_⟩")
    w(f"  · have hc : e{C[0]} ∈ M := by simp [h]")
    w("    exact absurd ((mem_M _).1 hc) (by decide +kernel)")
    w("  · obtain ⟨c, hcS, hcM⟩ := SetLike.exists_of_lt hS")
    w("    have hMS : M ≤ S := hS.le")
    for i in M:
        w(f"    have h{i} : e{i} ∈ S := hMS ((mem_M _).2 rfl)")
    w("    cases c with")
    for c in range(n):
        if c in M:
            w(f"    | e{c} => exact absurd ((mem_M _).2 rfl) hcM")
            continue
        w(f"    | e{c} =>")
        w(f"      have h{c} : e{c} ∈ S := hcS")
        for (z, op, a, b) in derivation(n, sup, inf, M + [c]):
            lem = "sup_mem" if op == "sup" else "inf_mem"
            w(f"      have h{z} : e{z} ∈ S := S.{lem} h{a} h{b}")
        w("      exact eq_top_iff.2 fun x _ => by cases x <;> assumption")
    w("")
    return out, le, sup, inf, M, C


